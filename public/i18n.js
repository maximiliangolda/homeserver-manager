let LANG = localStorage.getItem('hsm-lang') === 'en' ? 'en' : 'de';

function setLang(l) {
  LANG = l === 'en' ? 'en' : 'de';
  localStorage.setItem('hsm-lang', LANG);
  document.documentElement.lang = LANG;
}

const t = (key, ...args) => {
  const v = I18N[LANG][key] ?? I18N.de[key] ?? key;
  return typeof v === 'function' ? v(...args) : v;
};

const tLocale = () => LANG === 'en' ? 'en-GB' : 'de-DE';
